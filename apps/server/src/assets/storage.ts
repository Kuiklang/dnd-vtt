import { createReadStream } from "node:fs";
import { mkdir, rename, rm, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import type { Readable } from "node:stream";

/**
 * Object storage abstraction. Local disk in development; an S3/R2 implementation
 * can be dropped in later without touching services (same three methods).
 */
export interface Storage {
  put(key: string, data: Buffer, contentType: string): Promise<void>;
  /** `range` is inclusive byte offsets; `size` is always the whole object's size. */
  get(key: string, range?: { start: number; end: number }): Promise<{ stream: Readable; size: number } | null>;
  delete(key: string): Promise<void>;
}

/** Keys are generated by the server (`<campaign|user>/<uuid>`); still, refuse traversal. */
function safeKey(key: string): string {
  if (!/^[a-zA-Z0-9/_-]+$/.test(key) || key.includes("..") || key.startsWith("/")) throw new Error("Invalid storage key");
  return key;
}

export class LocalDiskStorage implements Storage {
  constructor(private readonly root: string) {}

  private file(key: string) {
    return path.join(this.root, safeKey(key));
  }

  async put(key: string, data: Buffer): Promise<void> {
    const target = this.file(key);
    await mkdir(path.dirname(target), { recursive: true });
    // Write-then-rename so readers never see a half-written file.
    const tmp = `${target}.tmp-${process.pid}-${Date.now()}`;
    await writeFile(tmp, data);
    await rename(tmp, target);
  }

  async get(key: string, range?: { start: number; end: number }) {
    const target = this.file(key);
    try {
      const s = await stat(target);
      return { stream: createReadStream(target, range), size: s.size };
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    await rm(this.file(key), { force: true });
  }
}
